const CATALOG = { es, en, de, tr };

let current = DEFAULT_LANG;
const pluralCache = {};

export function setLang(lang) {
  current = LANGS[lang] ? lang : DEFAULT_LANG;
  document.documentElement.lang = current;
  return current;
}
export function getLang() { return current; }
export function getLocale() { return LANGS[current].locale; }

function pluralCat(n) {
  if (!pluralCache[current]) pluralCache[current] = new Intl.PluralRules(getLocale());
  return pluralCache[current].select(n);
}

export function t(key, params = {}) {
  let v = CATALOG[current][key];
  if (v === undefined) v = CATALOG.es[key];
  if (v === undefined) return key;
  if (typeof v === 'object') v = v[pluralCat(Number(params.n) || 0)] ?? v.other;
  return v.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? String(params[k]) : m));
}

const fmtCache = {};
export function fmtDateTime(ts) {
  const loc = getLocale();
  if (!fmtCache[loc]) {
    fmtCache[loc] = new Intl.DateTimeFormat(loc, { weekday: 'short', day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });
  }
  return fmtCache[loc].format(new Date(ts));
}

// Aplica textos estáticos: data-i18n (textContent), data-i18n-aria, data-i18n-ph, data-i18n-title.
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.setAttribute('placeholder', t(el.dataset.i18nPh)); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.setAttribute('title', t(el.dataset.i18nTitle)); });
  document.title = t('docTitle');
}

export function catalogKeys(lang) { return Object.keys(CATALOG[lang] || {}); }
